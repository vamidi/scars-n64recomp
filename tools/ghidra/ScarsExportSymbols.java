// Exports Ghidra's discovered functions as an N64Recomp symbols TOML.
//
// Arguments:
//   1: output path
//   2: section start vram (hex, default 0x80200400)
//   3: section end vram, exclusive (hex, default 0x802B6050 = _bss_start)
//   4: section rom offset (hex, default 0x1000)
//
// The output is consumed through `symbols_file_path` in recomp/scars.toml,
// so N64Recomp never needs an ELF.

import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;

import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

public class ScarsExportSymbols extends GhidraScript {
    private static long parseHex(String s, long fallback) {
        if (s == null || s.isEmpty()) {
            return fallback;
        }
        String t = s.toLowerCase();
        if (t.startsWith("0x")) {
            t = t.substring(2);
        }
        try {
            return Long.parseUnsignedLong(t, 16);
        } catch (NumberFormatException e) {
            return fallback;
        }
    }

    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        String outPath = args.length > 0 ? args[0] : "scars.symbols.toml";
        long sectionStart = parseHex(args.length > 1 ? args[1] : null, 0x80200400L);
        long sectionEnd = parseHex(args.length > 2 ? args[2] : null, 0x802B6050L);
        long sectionRom = parseHex(args.length > 3 ? args[3] : null, 0x1000L);

        FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
        List<Function> funcs = new ArrayList<>();
        for (Function f : it) {
            if (f.isExternal() || f.isThunk()) {
                continue;
            }
            long start = f.getEntryPoint().getOffset();
            if (start < sectionStart || start >= sectionEnd) {
                continue;
            }
            if (f.getBody().getNumAddresses() <= 0) {
                continue;
            }
            funcs.add(f);
        }
        funcs.sort(Comparator.comparingLong(f -> f.getEntryPoint().getOffset()));

        long lastEnd = sectionStart;
        for (Function f : funcs) {
            long end = f.getBody().getMaxAddress().getOffset() + 1;
            if (end > lastEnd) {
                lastEnd = end;
            }
        }
        long sectionSize = lastEnd - sectionStart;
        sectionSize = (sectionSize + 3) & ~3L;

        try (PrintWriter w = new PrintWriter(outPath, "UTF-8")) {
            w.println("# Generated by ScarsExportSymbols.java from a local ROM dump.");
            w.println("# Input to N64Recomp (symbols_file_path). Do not redistribute.");
            w.println();
            w.println("[[section]]");
            w.println("name = \".boot\"");
            w.printf("rom = 0x%X%n", sectionRom);
            w.printf("vram = 0x%X%n", sectionStart);
            w.printf("size = 0x%X%n", sectionSize);
            w.println();
            for (Function f : funcs) {
                String name = f.getName();
                if (!name.matches("[A-Za-z_][A-Za-z0-9_]*")) {
                    name = String.format("func_%08X", f.getEntryPoint().getOffset());
                }
                long size = f.getBody().getNumAddresses();
                size = (size + 3) & ~3L;
                w.println("[[section.functions]]");
                w.printf("name = \"%s\"%n", name);
                w.printf("vram = 0x%X%n", f.getEntryPoint().getOffset());
                w.printf("size = 0x%X%n", size);
                w.println();
            }
        }

        println("ScarsExportSymbols: wrote " + funcs.size() + " functions, section size 0x"
                + Long.toHexString(sectionSize) + ", to " + outPath);
    }
}
